"""금액 문자열 정규화.

OCR로 읽은 금액은 '₩849,000', '849.000원' 처럼 통화기호/구분자/단위가 섞여 있다.
사용자 요구: 각 항목에서 온점('.')과 '원' 문자를 제거한다.
이 통장(신협)은 '₩'와 쉼표(',')도 사용하므로 함께 제거해 순수 정수로 만든다.
"""

import re


def to_amount(raw) -> int:
    """금액 문자열에서 숫자만 남겨 정수로 변환한다.

    예) '₩849,000' -> 849000 / '849.000원' -> 849000 / None -> 0
    """
    if raw is None:
        return 0
    digits = re.sub(r"[^\d]", "", str(raw))  # . , ₩ 원 공백 등 숫자가 아닌 문자 전부 제거
    return int(digits) if digits else 0
