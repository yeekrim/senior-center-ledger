"""OCR 원시 행(row)을 입금 / 지출 / 이자 3개 리스트로 분류한다.

핵심 규칙 (통장 컬럼 경계선 기준):
  - '찾으신금액' 칸에 값이 있으면  -> 지출 (돈이 나감)
  - '맡기신금액' 칸에 값이 있으면  -> 입금 (돈이 들어옴)
  - 적요/사용내역에 '결산이자'가 있으면 -> 이자 (별도 관리)
실제 OCR에서는 금액 텍스트 박스의 x좌표가 두 칸의 경계선 어느 쪽인지로 판별한다.
여기서는 이미 칸이 나뉜 row(dict)를 입력으로 받는다.

입력 row(dict) 필드:
  date, 적요, 찾으신금액, 맡기신금액, 사용내역, 잔액, 거래점

출력 레코드 형식 (사용자 스펙 — 날짜를 key로 하는 단일 항목 dict):
  지출: {date: [적요, 금액, 사용내역, 잔액, 거래점]}   # 지출은 '금액'이 먼저
  입금: {date: [적요, 사용내역, 금액, 잔액, 거래점]}   # 입금은 '사용내역'이 먼저
  이자: {date: [적요, 사용내역, 금액, 잔액, 거래점]}
※ 같은 날짜가 여러 번 나오므로(예: 20260530) 하나의 큰 dict가 아니라
  '단일 key dict의 리스트'로 담아 중복 날짜를 보존한다.
"""

from .normalize import to_amount

# 신협 통장의 결산 이자 표기. 다른 은행 통장을 다루면 그 은행의 표기를 확인해 바꾼다.
INTEREST_KEYWORD = "결산이자"


def classify_rows(rows):
    입금, 지출, 이자 = [], [], []

    for r in rows:
        date = r["date"]
        적요 = r.get("적요", "")
        내역 = r.get("사용내역", "")
        잔액 = to_amount(r.get("잔액"))
        거래점 = r.get("거래점", "")

        찾으신 = r.get("찾으신금액")
        맡기신 = r.get("맡기신금액")

        if INTEREST_KEYWORD in 내역 or INTEREST_KEYWORD in 적요:
            금액 = to_amount(맡기신) or to_amount(찾으신)
            이자.append({date: [적요, 내역, 금액, 잔액, 거래점]})
        elif 찾으신:  # 찾으신금액 칸에 값이 있음 -> 지출
            지출.append({date: [적요, to_amount(찾으신), 내역, 잔액, 거래점]})
        elif 맡기신:  # 맡기신금액 칸에 값이 있음 -> 입금
            입금.append({date: [적요, 내역, to_amount(맡기신), 잔액, 거래점]})
        # 두 칸 모두 비어 있으면(예: '신규' 개설 행) 거래가 아니므로 건너뛴다.

    return 입금, 지출, 이자
